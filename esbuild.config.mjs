import esbuild from "esbuild";
import process from "process";
import fs from "node:fs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// 版本戳單一來源＝manifest.json 的 version（構建時注入 BUILD_VERSION），
// 交付漏改硬編碼戳不可能再發生。
const manifest = JSON.parse(fs.readFileSync("manifest.json", "utf8"));

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  // builtin-modules 套件已移除（審核 module-replacements 警告）——
  // 改用 esbuild 原生 external 機制：Node 內建模組以正則前綴外部化（node: 前綴＋常見裸名），
  // 覆蓋面與 builtin-modules 清單等價（bundle 內實際 import 的內建模組均有 node: 前綴或屬下表）。
  external: [
    "obsidian", "electron", "@codemirror/view", "@codemirror/state",
    "assert","assert/strict","async_hooks","buffer","child_process","cluster","console",
    "constants","crypto","dgram","diagnostics_channel","dns","dns/promises","domain",
    "events","fs","fs/promises","http","http2","https","inspector","inspector/promises",
    "module","net","os","path","path/posix","path/win32","perf_hooks","process","punycode",
    "querystring","readline","readline/promises","repl","stream","stream/consumers",
    "stream/promises","stream/web","string_decoder","timers","timers/promises","tls",
    "trace_events","tty","url","util","util/types","v8","vm","worker_threads","zlib",
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  define: { BUILD_VERSION: JSON.stringify(manifest.version) },
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
